import {describe,it,expect} from 'vitest'
import {ArenaAdaptiveQuality,isArenaQualityMode,isArenaQuality} from '../snake-arena-quality'
import {readArenaMessage,SNAKE_CHANNEL,SNAKE_BUILD} from '../snake-arena-client'
const slow={fps:40,frameMsP95:45},healthy={fps:60,frameMsP95:18}
describe('adaptive arena effects',()=>{
  it('starts high and degrades one step only after consecutive active windows, with a cooldown',()=>{
    const q=new ArenaAdaptiveQuality()
    expect(q.observe(slow,0,true)).toBe('high')
    expect(q.observe(slow,2000,true)).toBe('high')
    expect(q.observe(slow,4000,true)).toBe('balanced')
    expect(q.observe(slow,6000,true)).toBe('balanced')
    expect(q.observe(slow,8000,true)).toBe('balanced')
    expect(q.observe(slow,10000,true)).toBe('low')
    expect(q.snapshot()).toMatchObject({mode:'auto',quality:'low',changes:2,reason:'slow'})
    expect(q.observe(slow,12000,true)).toBe('low')
  })
  it('an isolated slow frame or unstable threshold does not keep changing quality',()=>{
    const q=new ArenaAdaptiveQuality()
    q.observe(healthy,0,true)
    for(let i=1;i<=30;i++)q.observe(i%2?slow:healthy,i*2000,true)
    expect(q.snapshot()).toMatchObject({quality:'high',changes:0})
    q.observe({fps:57,frameMsP95:36},62000,true)
    expect(q.observe({fps:57,frameMsP95:36},64000,true)).toBe('balanced')
    for(let i=1;i<=20;i++)q.observe({fps:54,frameMsP95:25},64000+i*2000,true)
    expect(q.snapshot()).toMatchObject({quality:'balanced',changes:1})
  })
  it('recovers slowly by one level and requires a fresh sustained healthy run',()=>{
    const q=new ArenaAdaptiveQuality()
    q.observe(slow,0,true);q.observe(slow,2000,true);q.observe(slow,4000,true)
    for(let t=6000;t<24000;t+=2000)expect(q.observe(healthy,t,true)).toBe('balanced')
    expect(q.observe(healthy,24000,true)).toBe('high')
    expect(q.snapshot().reason).toBe('recovered')
    q.select('low',25000);q.select('auto',25000);q.observe(healthy,45000,true)
    for(let t=47000;t<=55000;t+=2000)expect(q.observe(healthy,t,true)).toBe('low')
    expect(q.observe(healthy,57000,true)).toBe('balanced')
  })
  it('death, hidden tabs, missing snapshots and interrupted windows cannot cause a downgrade',()=>{
    const q=new ArenaAdaptiveQuality()
    q.observe(slow,0,true);q.observe(slow,2000,true)
    q.observe(slow,4000,false);q.observe(slow,6000,true)
    expect(q.observe(slow,8000,true)).toBe('high')
    expect(q.observe(slow,20000,true)).toBe('high')
    expect(q.observe(slow,22000,true)).toBe('high')
    q.pause();q.observe(slow,24000,true)
    expect(q.observe(slow,26000,true)).toBe('high')
    expect(q.observe(slow,28000,true)).toBe('balanced')
    q.pause();for(let t=30000;t<60000;t+=2000)q.observe({fps:1},t,false)
    expect(q.quality).toBe('balanced')
  })
  it('ignores duplicates and rejects invalid samples without carrying a slow streak',()=>{
    const q=new ArenaAdaptiveQuality();q.observe(slow,0,true);q.observe(slow,2000,true)
    for(let t=2100;t<3000;t+=100)q.observe(slow,t,true)
    expect(q.quality).toBe('high')
    q.observe({fps:NaN},4000,true);q.observe(slow,6000,true)
    expect(q.observe(slow,8000,true)).toBe('high')
    q.observe({fps:40,frameMsP95:-1},10000,true);q.observe(slow,12000,true)
    expect(q.observe(slow,14000,true)).toBe('high')
    q.observe(slow,13000,true);q.observe(slow,16000,true)
    expect(q.observe(slow,18000,true)).toBe('high')
  })
  it('manual preferences apply immediately, stay fixed and automatic resumes from the chosen level',()=>{
    const q=new ArenaAdaptiveQuality();expect(q.select('low',0)).toBe('low')
    for(let t=2000;t<=30000;t+=2000)q.observe(healthy,t,true)
    expect(q.quality).toBe('low')
    expect(q.select('high',32000)).toBe('high')
    for(let t=34000;t<=60000;t+=2000)q.observe(slow,t,true)
    expect(q.quality).toBe('high')
    expect(q.select('auto',62000)).toBe('high')
    q.observe(slow,64000,true);q.observe(slow,66000,true)
    expect(q.observe(slow,68000,true)).toBe('balanced')
  })
  it('validates stored modes and effective renderer acknowledgements without breaking older telemetry',()=>{
    for(const q of ['high','balanced','low']){expect(isArenaQuality(q)).toBe(true);expect(isArenaQualityMode(q)).toBe(true)}
    expect(isArenaQualityMode('auto')).toBe(true);expect(isArenaQuality('auto')).toBe(false)
    for(const bad of [null,{},1,'ultra','HIGH'])expect(isArenaQualityMode(bad)).toBe(false)
    const wrap=(quality:unknown)=>({channel:SNAKE_CHANNEL,version:1,build:SNAKE_BUILD,data:{v:1,type:'fps',fps:60,quality}})
    expect(readArenaMessage(wrap('balanced'))?.quality).toBe('balanced')
    expect(readArenaMessage(wrap(undefined))).not.toBeNull()
    for(const bad of ['auto','ultra',1,null])expect(readArenaMessage(wrap(bad))).toBeNull()
  })
})
