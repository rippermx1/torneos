import { randomUUID } from 'node:crypto'
import assert from 'node:assert/strict'

export async function verifyOperationsCases({ checked, denied, check, source, service, fixture, sql }) {
  await checked(await source('supabase/migrations/20260706000000_cron_heartbeats.sql'))
  await checked(await source('supabase/migrations/20261005160247_operational_obligations_and_alerts.sql'))
  const last=async text=>(await checked(text)).split('\n').at(-1)
  const observe=service("SELECT observe_operations('primary@example.test','backup@example.test');")
  const fresh=async()=>{for(const job of ['process-tournaments','flow-reconcile','reconcile-refunds'])await checked(service(`SELECT record_cron_execution('${job}','ok');`))}
  const active=key=>last(`SELECT count(*) FROM ops_incidents WHERE condition_key='${key}' AND resolved_at IS NULL;`)
  const snapshot=async()=>JSON.parse(await last(service('SELECT operational_snapshot();')))
  await check('RM09 no client reads or writes; service cannot bypass RPC or delete audit',async()=>{
    for(const role of ['anon','authenticated','service_role'])for(const table of ['ops_incidents','ops_notifications','ops_incident_events','cron_heartbeats']) {
      await denied(`SET ROLE ${role}; DELETE FROM ${table};`,'permission denied')
      if(role!=='service_role')await denied(`SET ROLE ${role}; SELECT * FROM ${table};`,'permission denied')
    }
    assert.equal(await last("SELECT count(*) FROM pg_proc WHERE proname IN ('record_cron_execution','operational_snapshot','observe_operations','acknowledge_ops_incident','claim_ops_notifications','finish_ops_notification') AND (has_function_privilege('authenticated',oid,'EXECUTE') OR NOT ('search_path=\"\"'=ANY(proconfig)));"),'0')
    await denied(service("SELECT private.enqueue_ops_notification(gen_random_uuid(),'opened','x');"),'permission denied')
  })
  await check('missing processing success opens incidents; repeated observation deduplicates notifications',async()=>{
    await checked(observe);await checked(observe)
    for(const job of ['process-tournaments','flow-reconcile','reconcile-refunds'])assert.equal(await active(`job:${job}`),'1')
    assert.equal(await last("SELECT count(*) FROM ops_notifications n JOIN ops_incidents i ON i.id=n.incident_id WHERE i.condition_key LIKE 'job:%' AND n.stage='opened';"),'3')
    await fresh();await checked(observe)
    assert.equal(await last("SELECT count(*) FROM ops_incidents WHERE condition_key LIKE 'job:%' AND resolved_at IS NULL;"),'0')
  })
  await check('start and repeated error never advance last success; threshold is two failures or 15 minutes',async()=>{
    await fresh(); const prior=await last("SELECT last_success_at FROM cron_heartbeats WHERE job_name='flow-reconcile';")
    await checked(service("SELECT record_cron_execution('flow-reconcile','started'); SELECT record_cron_execution('flow-reconcile','error','fixture');"))
    await checked(observe);assert.equal(await active('job:flow-reconcile'),'0')
    assert.equal(await last("SELECT last_success_at FROM cron_heartbeats WHERE job_name='flow-reconcile';"),prior)
    await checked(service("SELECT record_cron_execution('flow-reconcile','error','fixture');"));await checked(observe)
    assert.equal(await active('job:flow-reconcile'),'1')
    await fresh();await checked(observe)
    await checked(service("SELECT record_cron_dispatch_failure('flow-reconcile');"));await checked(observe)
    assert.equal(await active('job:flow-reconcile'),'0')
    assert.equal(await last("SELECT consecutive_failures FROM cron_heartbeats WHERE job_name='flow-reconcile';"),'0')
    await checked(service("SELECT record_cron_dispatch_failure('flow-reconcile');"));await checked(observe)
    assert.equal(await active('job:flow-reconcile'),'1');await fresh();await checked(observe)
    await checked("UPDATE cron_heartbeats SET last_success_at=now()-interval '16 minutes',last_run_at=now() WHERE job_name='flow-reconcile';")
    await checked(observe);assert.equal(await active('job:flow-reconcile'),'1');await fresh();await checked(observe)
  })
  const f=await fixture(),attempt=randomUUID()
  await checked(`INSERT INTO flow_payment_attempts(id,user_id,tournament_id,commerce_order,charged_amount_cents,net_amount_cents,status,created_at)
    VALUES('${attempt}','${f.user}','${f.tournament}','ops-${attempt}',123456,123456,'unknown',now()-interval '31 minutes');`)
  await check('aggregate amounts and oldest date expose unknown obligations while processing succeeds',async()=>{
    await fresh(); await checked(observe)
    const q=(await snapshot()).queues.find(q=>q.key==='unknown-payments')
    assert.equal(q.amount_cents,123456);assert.equal(q.count,1);assert.ok(q.oldest_at)
    assert.equal(await active('unknown-payments'),'1')
    assert.equal(await last("SELECT count(*) FROM ops_incidents WHERE condition_key LIKE 'job:%' AND resolved_at IS NULL;"),'0')
    assert.equal((await snapshot()).bank_cash_verified,false)
  })
  const incident=await last("SELECT id FROM ops_incidents WHERE condition_key='unknown-payments' AND resolved_at IS NULL;")
  const actor=await fixture(),other=await fixture();await checked(`INSERT INTO profile_roles VALUES('${actor.user}','admin'),('${other.user}','admin');`)
  const ack=(who=actor.user)=>service(`SELECT acknowledge_ops_incident('${incident}','${who}','Revisar evidencia Flow y contactar al proveedor');`)
  await check('30 minute escalation is persistent once and addressed to backup; acknowledgement does not clear debt',async()=>{
    await checked(`UPDATE ops_incidents SET first_seen_at=now()-interval '31 minutes',critical_since=now()-interval '31 minutes' WHERE id='${incident}';`)
    await checked(observe);await checked(observe)
    assert.equal(await last(`SELECT count(*) FROM ops_notifications WHERE incident_id='${incident}' AND stage='escalated' AND recipient='backup@example.test';`),'1')
    await checked(ack());await checked(ack());await checked(observe)
    assert.equal(await active('unknown-payments'),'1')
    assert.equal(await last(`SELECT count(*) FROM ops_incident_events WHERE incident_id='${incident}' AND action='acknowledged';`),'1')
    await denied(ack(other.user),'otro operador')
  })
  await check('fresh ban or role revocation forbids acknowledgement',async()=>{
    await checked(`UPDATE profiles SET is_banned=true WHERE id='${other.user}';`);await denied(ack(other.user),'Operador')
    await checked(`UPDATE profiles SET is_banned=false WHERE id='${other.user}'; DELETE FROM profile_roles WHERE profile_id='${other.user}' AND role='admin';`)
    await denied(ack(other.user),'Operador')
  })
  await check('recovery closes only observed condition; recurrence creates new episode/key',async()=>{
    await checked(`UPDATE flow_payment_attempts SET status='pending',created_at=now() WHERE id='${attempt}';`);await checked(observe)
    assert.equal(await active('unknown-payments'),'0')
    assert.equal(await last(`SELECT count(*) FROM ops_notifications WHERE incident_id='${incident}' AND stage='recovered';`),'1')
    await denied(ack(),'recuperado')
    await checked(`UPDATE flow_payment_attempts SET status='unknown',created_at=now()-interval '31 minutes' WHERE id='${attempt}';`);await checked(observe)
    assert.equal(await last("SELECT count(*) FROM ops_incidents WHERE condition_key='unknown-payments';"),'2')
  })
  await check('concurrent observers create exactly one episode and no repeated initial notification',async()=>{
    const results=await Promise.all([sql(observe),sql(observe)]);results.forEach(r=>assert.equal(r.code,0,r.err))
    assert.equal(await active('unknown-payments'),'1')
    assert.equal(await last("SELECT count(*) FROM ops_notifications n JOIN ops_incidents i ON i.id=n.incident_id WHERE i.condition_key='unknown-payments' AND i.resolved_at IS NULL AND stage='opened';"),'1')
  })
  await check('core audit insertion failure rolls back incident and outbox together',async()=>{
    await checked(`UPDATE cron_heartbeats SET last_success_at=now()-interval '16 minutes' WHERE job_name='process-tournaments';
      CREATE FUNCTION private.fail_ops_event() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'injected ops audit failure'; END; $$;
      CREATE TRIGGER fail_ops_event BEFORE INSERT ON ops_incident_events FOR EACH ROW EXECUTE FUNCTION private.fail_ops_event();`)
    await denied(observe,'injected ops audit failure');assert.equal(await active('job:process-tournaments'),'0')
    await checked('DROP TRIGGER fail_ops_event ON ops_incident_events; DROP FUNCTION private.fail_ops_event();');await fresh()
  })
  await check('a real accounting difference alerts immediately without asserting bank liquidity',async()=>{
    const id=await last("WITH inserted AS (INSERT INTO accounting_journal_entries(event_key) VALUES('ops-difference') RETURNING id) SELECT id FROM inserted;")
    await checked(`INSERT INTO accounting_postings(journal_entry_id,account_code,debit_cents,credit_cents) VALUES(${id},'110100',98765,0);`)
    await checked(observe);assert.equal(await active('ledger-difference'),'1')
    const q=(await snapshot()).checks.find(q=>q.key==='ledger-difference');assert.ok(q.amount_cents>=98765)
    await checked(`INSERT INTO accounting_postings(journal_entry_id,account_code,debit_cents,credit_cents) VALUES(${id},'210200',0,98765);`)
    await checked(observe);assert.equal(await active('ledger-difference'),'0')
  })
  await check('concurrent notification claims cannot send same row; lost response reuses immutable id and payload',async()=>{
    const claimed=await Promise.all([last(service('SELECT jsonb_agg(n) FROM claim_ops_notifications() n;')),last(service('SELECT jsonb_agg(n) FROM claim_ops_notifications() n;'))])
    const rows=claimed.flatMap(x=>JSON.parse(x)||[]);assert.equal(new Set(rows.map(x=>x.id)).size,rows.length);assert.ok(rows.length>0)
    const n=rows[0];await denied(service(`SELECT finish_ops_notification('${n.id}','${randomUUID()}','provider-1');`),'Arrendamiento')
    await checked(`UPDATE ops_notifications SET lease_until=now()-interval '1 minute',next_attempt_at=now()-interval '100 days' WHERE id='${n.id}';`)
    const repeated=(JSON.parse(await last(service('SELECT jsonb_agg(n) FROM claim_ops_notifications() n;')))||[]).find(x=>x.id===n.id)
    assert.ok(repeated);assert.equal(repeated.text_body,n.text_body);assert.equal(repeated.recipient,n.recipient);assert.notEqual(repeated.claim_token,n.claim_token)
    await denied(service(`SELECT finish_ops_notification('${n.id}','${n.claim_token}','old-provider');`),'Arrendamiento')
    await checked(service(`SELECT finish_ops_notification('${n.id}','${repeated.claim_token}','provider-1');`))
    assert.equal(await last(`SELECT state FROM ops_notifications WHERE id='${n.id}';`),'accepted')
  })
  await check('uncertain notifications past idempotency window are blocked and channel failure is durable',async()=>{
    await checked("UPDATE ops_notifications SET first_attempt_at=now()-interval '24 hours',lease_until=NULL WHERE state<>'accepted';")
    await checked(service('SELECT count(*) FROM claim_ops_notifications();'));await checked(observe)
    assert.equal(await active('notification-channel'),'1')
    assert.ok(Number(await last("SELECT count(*) FROM ops_notifications WHERE state='blocked';"))>0)
  })
  await check('manual alternate receipt is audited separately; expired uncertainty cannot be resent',async()=>{
    const n=await last("SELECT id FROM ops_notifications WHERE state='blocked' LIMIT 1;")
    await denied(service(`SELECT review_ops_notification('${n}','${actor.user}','retry','Provider checked and configuration fixed');`),'Ventana')
    await checked(service(`SELECT review_ops_notification('${n}','${actor.user}','manual_receipt','Operator contacted by phone, incident reviewed and received');`))
    assert.equal(await last(`SELECT state FROM ops_notifications WHERE id='${n}';`),'received_manually')
    assert.equal(await last(`SELECT count(*) FROM ops_notifications WHERE id='${n}' AND provider_id IS NULL AND accepted_at IS NULL AND reviewed_by='${actor.user}';`),'1')
    assert.equal(await last(`SELECT count(*) FROM ops_incident_events WHERE actor_id='${actor.user}' AND action='manual_receipt';`),'1')
  })
  await check('orphan withdrawal debit opens immediate critical incident',async()=>{
    const id=randomUUID()
    await checked(`INSERT INTO wallet_transactions(user_id,type,amount_cents,reference_type,reference_id) VALUES('${f.user}','withdrawal',-54321,'withdrawal_request','${id}');`)
    await checked(observe);assert.equal(await active('orphan-debit'),'1')
    assert.equal((await snapshot()).checks.find(q=>q.key==='orphan-debit').amount_cents>=54321,true)
    await checked(`DELETE FROM wallet_transactions WHERE reference_id='${id}';`);await checked(observe)
    assert.equal(await active('orphan-debit'),'0')
  })
  await check('historical duplicate credits and missing independent payout authorization alert immediately',async()=>{
    await checked(`INSERT INTO wallet_transactions(user_id,type,amount_cents,reference_type,reference_id)
      VALUES('${f.user}','prize_credit',99999,'tournament','${f.tournament}'),('${f.user}','prize_credit',99999,'tournament','${f.tournament}');`)
    await checked(observe);assert.equal(await active('duplicate-prize'),'1')
    await checked(`DELETE FROM wallet_transactions WHERE user_id='${f.user}' AND type='prize_credit';`)
    const payout=JSON.parse(await last("SELECT row_to_json(w) FROM withdrawal_requests w WHERE status='approved' LIMIT 1;"))
    assert.ok(payout)
    await checked(`UPDATE withdrawal_requests SET reviewed_by=claimed_by WHERE id='${payout.id}';`)
    await checked(observe);assert.equal(await active('unauthorized-payout'),'1')
    await checked(`UPDATE withdrawal_requests SET reviewed_by='${payout.reviewed_by}' WHERE id='${payout.id}';`)
    await checked(observe);assert.equal(await active('duplicate-prize'),'0');assert.equal(await active('unauthorized-payout'),'0')
  })
  await check('source read error cannot auto recover active incidents',async()=>{
    await checked('ALTER TABLE flow_payment_attempts RENAME TO fixture_unavailable_payments;')
    await denied(observe,'flow_payment_attempts');assert.equal(await active('unknown-payments'),'1')
    await checked('ALTER TABLE fixture_unavailable_payments RENAME TO flow_payment_attempts;')
  })
}
